void eraLtp(double epochJ,double rp[3][3]){
	double equator_pole[3];
	double ecliptic_pole[3];
	double cross1[3];
	double equinox[3];
	double r;

	eraLtpequ(epochJ,equator_pole);
	eraLtpecl(epochJ,ecliptic_pole);

	eraPxp(equator_pole,ecliptic_pole,cross1);
	eraPn(cross1,&r,equinox);

	eraPxp(equator_pole,equinox,cross1);

	for(int i=0;i<3;++i){
		rp[0][i]=equinox[i];
		rp[1][i]=cross1[i];
		rp[2][i]=equator_pole[i];
	}
}

