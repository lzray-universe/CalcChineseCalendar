void eraSxp(double s,double p[3],double sp[3]){
	sp[0]=s*p[0];
	sp[1]=s*p[1];
	sp[2]=s*p[2];
}

double eraPm(double p[3]){ return sqrt(p[0]*p[0]+p[1]*p[1]+p[2]*p[2]); }

void eraPn(double p[3],double*r,double u[3]){
	const double mod=eraPm(p);
	if(mod==0.0){
		eraZp(u);
	}else{
		eraSxp(1.0/mod,p,u);
	}
	*r=mod;
}

void eraPxp(double a[3],double b[3],double axb[3]){
	const double ax=a[0];
	const double ay=a[1];
	const double az=a[2];
	const double bx=b[0];
	const double by=b[1];
	const double bz=b[2];

	axb[0]=ay*bz-az*by;
	axb[1]=az*bx-ax*bz;
	axb[2]=ax*by-ay*bx;
}

void eraCp(double p[3],double c[3]){
	c[0]=p[0];
	c[1]=p[1];
	c[2]=p[2];
}

double eraPdp(double a[3],double b[3]){ return a[0]*b[0]+a[1]*b[1]+a[2]*b[2]; }

void eraPmp(double a[3],double b[3],double amb[3]){
	amb[0]=a[0]-b[0];
	amb[1]=a[1]-b[1];
	amb[2]=a[2]-b[2];
}

void eraPpsp(double a[3],double s,double b[3],double apsb[3]){
	apsb[0]=a[0]+s*b[0];
	apsb[1]=a[1]+s*b[1];
	apsb[2]=a[2]+s*b[2];
}

void eraLd(double bm,double p[3],double q[3],double e[3],double em,double dlim,
		   double p1[3]){
	double qPlusE[3];
	qPlusE[0]=q[0]+e[0];
	qPlusE[1]=q[1]+e[1];
	qPlusE[2]=q[2]+e[2];

	const double qDot=q[0]*qPlusE[0]+q[1]*qPlusE[1]+q[2]*qPlusE[2];
	const double denom=(qDot>dlim)?qDot:dlim;
	const double scale=bm*K_SUN_SCHWARZSCHILD_AU/em/denom;

	double exq[3];
	double pxexq[3];
	eraPxp(e,q,exq);
	eraPxp(p,exq,pxexq);

	p1[0]=p[0]+scale*pxexq[0];
	p1[1]=p[1]+scale*pxexq[1];
	p1[2]=p[2]+scale*pxexq[2];
}

void eraLdn(int n,eraLDBODY b[],double ob[3],double sc[3],double sn[3]){
	eraCp(sc,sn);

	for(int i=0;i<n;++i){
		double bodyToObserver[3];
		eraPmp(ob,b[i].pv[0],bodyToObserver);

		double dt=eraPdp(sn,bodyToObserver)*K_AU_LIGHT_TIME_DAYS;
		if(dt>0.0){
			dt=0.0;
		}

		double shiftedBodyToObserver[3];
		eraPpsp(bodyToObserver,-dt,b[i].pv[1],shiftedBodyToObserver);

		double em;
		double e[3];
		eraPn(shiftedBodyToObserver,&em,e);

		eraLd(b[i].bm,sn,sn,e,em,b[i].dl,sn);
	}
}

