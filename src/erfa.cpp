void eraAtioq(double ri,double di,eraASTROM*astrom,double*aob,double*zob,
			  double*hob,double*dob,double*rob){
	static constexpr double kCosAltMin=1e-6;
	static constexpr double kSinAltMin=0.05;

	double v[3];
	eraS2c(ri-astrom->eral,di,v);

	const double x=v[0];
	const double y=v[1];
	double z=v[2];

	const double sx=sin(astrom->xpl);
	const double cx=cos(astrom->xpl);
	const double sy=sin(astrom->ypl);
	const double cy=cos(astrom->ypl);

	const double xhd=cx*x+sx*z;
	const double yhd=sx*sy*x+cy*y-cx*sy*z;
	const double zhd=-sx*cy*x+sy*y+cx*cy*z;

	double f=1.0-astrom->diurab*yhd;
	const double xhdt=f*xhd;
	const double yhdt=f*(yhd+astrom->diurab);
	const double zhdt=f*zhd;

	const double xaet=astrom->sphi*xhdt-astrom->cphi*zhdt;
	const double yaet=yhdt;
	const double zaet=astrom->cphi*xhdt+astrom->sphi*zhdt;

	const double azobs=((xaet!=0.0)||(yaet!=0.0))?atan2(yaet,-xaet):0.0;

	double r=sqrt(xaet*xaet+yaet*yaet);
	r=(r>kCosAltMin)?r:kCosAltMin;
	z=(zaet>kSinAltMin)?zaet:kSinAltMin;

	const double tz=r/z;
	const double w=astrom->refb*tz*tz;
	const double del=(astrom->refa+w)*tz/(1.0+(astrom->refa+3.0*w)/(z*z));

	const double cosdel=1.0-del*del/2.0;
	f=cosdel-del*z/r;
	const double xaeo=xaet*f;
	const double yaeo=yaet*f;
	const double zaeo=cosdel*zaet+del*r;

	const double zdobs=atan2(sqrt(xaeo*xaeo+yaeo*yaeo),zaeo);

	v[0]=astrom->sphi*xaeo+astrom->cphi*zaeo;
	v[1]=yaeo;
	v[2]=-astrom->cphi*xaeo+astrom->sphi*zaeo;

	double hmobs;
	double dcobs;
	eraC2s(v,&hmobs,&dcobs);
	const double raobs=astrom->eral+hmobs;

	*aob=eraAnp(azobs);
	*zob=zdobs;
	*hob=-hmobs;
	*dob=dcobs;
	*rob=eraAnp(raobs);
}

