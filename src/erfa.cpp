static inline void fastSinCos(double x,double&s,double&c){
#if defined(__has_builtin)
#	if __has_builtin(__builtin_sincos)
	__builtin_sincos(x,&s,&c);
	return;
#	endif
#endif
	s=sin(x);
	c=cos(x);
}

