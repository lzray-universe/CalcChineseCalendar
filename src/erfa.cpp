void eraPmpx(double rc,double dc,double pr,double pd,double px,double rv,
			 double pmt,double pob[3],double pco[3]){
	static constexpr double kRadialKmpsToAuPerYear=
		K_SECONDS_PER_DAY*K_DAYS_PER_JULIAN_MILLENNIUM/K_AU_METERS;
	static constexpr double kOneAuLightTimeYears=
		K_AU_LIGHT_TIME_SECONDS/K_SECONDS_PER_DAY/K_DAYS_PER_JULIAN_YEAR;

	const double sr=sin(rc);
	const double cr=cos(rc);
	const double sd=sin(dc);
	const double cd=cos(dc);

	double p[3];
	p[0]=cr*cd;
	p[1]=sr*cd;
	p[2]=sd;

	const double dt=pmt+eraPdp(p,pob)*kOneAuLightTimeYears;
	const double parallaxRad=px*K_ARCSEC_TO_RAD;
	const double radialTerm=kRadialKmpsToAuPerYear*rv*parallaxRad;
	const double pdz=pd*p[2];

	double pm[3];
	pm[0]=-pr*p[1]-pdz*cr+radialTerm*p[0];
	pm[1]=pr*p[0]-pdz*sr+radialTerm*p[1];
	pm[2]=pd*cd+radialTerm*p[2];

	for(int i=0;i<3;++i){
		p[i]+=dt*pm[i]-parallaxRad*pob[i];
	}

	double w;
	eraPn(p,&w,pco);
}

void eraAb(double pnat[3],double v[3],double s,double bm1,double ppr[3]){
	const double pdv=eraPdp(pnat,v);
	const double w1=1.0+pdv/(1.0+bm1);
	const double w2=K_SUN_SCHWARZSCHILD_AU/s;

	double p[3];
	double r2=0.0;
	for(int i=0;i<3;++i){
		const double w=pnat[i]*bm1+w1*v[i]+w2*(v[i]-pdv*pnat[i]);
		p[i]=w;
		r2+=w*w;
	}

	const double r=sqrt(r2);
	ppr[0]=p[0]/r;
	ppr[1]=p[1]/r;
	ppr[2]=p[2]/r;
}

