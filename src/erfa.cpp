void eraIr(double r[3][3]){
	for(int row=0;row<3;++row){
		for(int col=0;col<3;++col){
			r[row][col]=(row==col)?1.0:0.0;
		}
	}
}

void eraRx(double phi,double r[3][3]){
	double s;
	double c;
	fastSinCos(phi,s,c);

	const double r10=c*r[1][0]+s*r[2][0];
	const double r11=c*r[1][1]+s*r[2][1];
	const double r12=c*r[1][2]+s*r[2][2];
	const double r20=-s*r[1][0]+c*r[2][0];
	const double r21=-s*r[1][1]+c*r[2][1];
	const double r22=-s*r[1][2]+c*r[2][2];

	r[1][0]=r10;
	r[1][1]=r11;
	r[1][2]=r12;
	r[2][0]=r20;
	r[2][1]=r21;
	r[2][2]=r22;
}

void eraRz(double psi,double r[3][3]){
	double s;
	double c;
	fastSinCos(psi,s,c);

	const double r00=c*r[0][0]+s*r[1][0];
	const double r01=c*r[0][1]+s*r[1][1];
	const double r02=c*r[0][2]+s*r[1][2];
	const double r10=-s*r[0][0]+c*r[1][0];
	const double r11=-s*r[0][1]+c*r[1][1];
	const double r12=-s*r[0][2]+c*r[1][2];

	r[0][0]=r00;
	r[0][1]=r01;
	r[0][2]=r02;
	r[1][0]=r10;
	r[1][1]=r11;
	r[1][2]=r12;
}

void eraZp(double p[3]){
	p[0]=0.0;
	p[1]=0.0;
	p[2]=0.0;
}

void eraSxp(double s,double p[3],double sp[3]){
	sp[0]=s*p[0];
	sp[1]=s*p[1];
	sp[2]=s*p[2];
}

double eraPm(double p[3]){ return sqrt(p[0]*p[0]+p[1]*p[1]+p[2]*p[2]); }

void eraPn(double p[3],double*r,double u[3]){
	const double mod=eraPm(p);
	if(mod==0.0){
		eraZp(u);
	}else{
		eraSxp(1.0/mod,p,u);
	}
	*r=mod;
}

void eraPxp(double a[3],double b[3],double axb[3]){
	const double ax=a[0];
	const double ay=a[1];
	const double az=a[2];
	const double bx=b[0];
	const double by=b[1];
	const double bz=b[2];

	axb[0]=ay*bz-az*by;
	axb[1]=az*bx-ax*bz;
	axb[2]=ax*by-ay*bx;
}

