void eraLtpecl(double epochJ,double vec[3]){
	static constexpr double eps0=84381.406*K_ARCSEC_TO_RAD;

	static const double pqpol[2][4]={
		{5851.607687,-0.1189000,-0.00028913,0.000000101},
		{-1600.886300,1.1689818,-0.00000020,-0.000000437},
	};

	static const double pqper[][5]={
		{708.15,-5486.751211,-684.661560,667.666730,-5523.863691},
		{2309.00,-17.127623,2446.283880,-2354.886252,-549.747450},
		{1620.00,-617.517403,399.671049,-428.152441,-310.998056},
		{492.20,413.442940,-356.652376,376.202861,421.535876},
		{1183.00,78.614193,-186.387003,184.778874,-36.776172},
		{622.00,-180.732815,-316.800070,335.321713,-145.278396},
		{882.00,-87.676083,198.296701,-185.138669,-34.744450},
		{547.00,46.140315,101.135679,-120.972830,22.885731},
	};

	const int nper=static_cast<int>(sizeof(pqper)/sizeof(pqper[0]));

	const double t=(epochJ-2000.0)/100.0;
	double p=0.0;
	double q=0.0;

	const double w_period=K_TWO_PI*t;
	for(int i=0;i<nper;++i){
		const double a=w_period/pqper[i][0];
		const double s=sin(a);
		const double c=cos(a);
		p+=c*pqper[i][1]+s*pqper[i][3];
		q+=c*pqper[i][2]+s*pqper[i][4];
	}

	double wt=1.0;
	for(int i=0;i<4;++i){
		p+=pqpol[0][i]*wt;
		q+=pqpol[1][i]*wt;
		wt*=t;
	}

	p*=K_ARCSEC_TO_RAD;
	q*=K_ARCSEC_TO_RAD;

	const double w=1.0-p*p-q*q;
	const double z=(w<0.0)?0.0:sqrt(w);
	double s;
	double c;
	fastSinCos(eps0,s,c);

	vec[0]=p;
	vec[1]=-q*c-z*s;
	vec[2]=-q*s+z*c;
}

