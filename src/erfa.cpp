void eraIr(double r[3][3]){
	for(int row=0;row<3;++row){
		for(int col=0;col<3;++col){
			r[row][col]=(row==col)?1.0:0.0;
		}
	}
}

void eraRx(double phi,double r[3][3]){
	double s;
	double c;
	fastSinCos(phi,s,c);

	const double r10=c*r[1][0]+s*r[2][0];
	const double r11=c*r[1][1]+s*r[2][1];
	const double r12=c*r[1][2]+s*r[2][2];
	const double r20=-s*r[1][0]+c*r[2][0];
	const double r21=-s*r[1][1]+c*r[2][1];
	const double r22=-s*r[1][2]+c*r[2][2];

	r[1][0]=r10;
	r[1][1]=r11;
	r[1][2]=r12;
	r[2][0]=r20;
	r[2][1]=r21;
	r[2][2]=r22;
}

void eraRz(double psi,double r[3][3]){
	double s;
	double c;
	fastSinCos(psi,s,c);

	const double r00=c*r[0][0]+s*r[1][0];
	const double r01=c*r[0][1]+s*r[1][1];
	const double r02=c*r[0][2]+s*r[1][2];
	const double r10=-s*r[0][0]+c*r[1][0];
	const double r11=-s*r[0][1]+c*r[1][1];
	const double r12=-s*r[0][2]+c*r[1][2];

	r[0][0]=r00;
	r[0][1]=r01;
	r[0][2]=r02;
	r[1][0]=r10;
	r[1][1]=r11;
	r[1][2]=r12;
}

void eraRy(double theta,double r[3][3]){
	double s;
	double c;
	fastSinCos(theta,s,c);

	const double r00=c*r[0][0]-s*r[2][0];
	const double r01=c*r[0][1]-s*r[2][1];
	const double r02=c*r[0][2]-s*r[2][2];
	const double r20=s*r[0][0]+c*r[2][0];
	const double r21=s*r[0][1]+c*r[2][1];
	const double r22=s*r[0][2]+c*r[2][2];

	r[0][0]=r00;
	r[0][1]=r01;
	r[0][2]=r02;
	r[2][0]=r20;
	r[2][1]=r21;
	r[2][2]=r22;
}

void eraZp(double p[3]){
	p[0]=0.0;
	p[1]=0.0;
	p[2]=0.0;
}

int eraEform(int n,double*a,double*f){
	switch(n){
	case K_ERFA_WGS84:
		*a=6378137.0;
		*f=1.0/298.257223563;
		break;
	case K_ERFA_GRS80:
		*a=6378137.0;
		*f=1.0/298.257222101;
		break;
	case K_ERFA_WGS72:
		*a=6378135.0;
		*f=1.0/298.26;
		break;
	default:
		*a=0.0;
		*f=0.0;
		return -1;
	}
	return 0;
}

int eraGd2gce(double a,double f,double elong,double phi,double height,
			  double xyz[3]){
	const double sp=sin(phi);
	const double cp=cos(phi);
	double w=1.0-f;
	w*=w;
	const double d=cp*cp+w*sp*sp;
	if(d<=0.0){
		return -1;
	}

	const double ac=a/sqrt(d);
	const double as=w*ac;
	const double r=(ac+height)*cp;

	xyz[0]=r*cos(elong);
	xyz[1]=r*sin(elong);
	xyz[2]=(as+height)*sp;
	return 0;
}

int eraGd2gc(int n,double elong,double phi,double height,double xyz[3]){
	double a;
	double f;
	int status=eraEform(n,&a,&f);
	if(status==0){
		status=eraGd2gce(a,f,elong,phi,height,xyz);
		if(status!=0){
			status=-2;
		}
	}
	if(status!=0){
		eraZp(xyz);
	}
	return status;
}

