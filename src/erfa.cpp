void eraS2c(double theta,double phi,double c[3]){
	const double cp=cos(phi);
	c[0]=cos(theta)*cp;
	c[1]=sin(theta)*cp;
	c[2]=sin(phi);
}

void eraC2s(double p[3],double*theta,double*phi){
	const double x=p[0];
	const double y=p[1];
	const double z=p[2];
	const double d2=x*x+y*y;

	*theta=(d2==0.0)?0.0:atan2(y,x);
	*phi=(z==0.0)?0.0:atan2(z,sqrt(d2));
}

void eraS2pv(double theta,double phi,double r,double td,double pd,double rd,
			 double pv[2][3]){
	const double st=sin(theta);
	const double ct=cos(theta);
	const double sp=sin(phi);
	const double cp=cos(phi);
	const double rcp=r*cp;
	const double x=rcp*ct;
	const double y=rcp*st;
	const double rpd=r*pd;
	const double w=rpd*sp-cp*rd;

	pv[0][0]=x;
	pv[0][1]=y;
	pv[0][2]=r*sp;
	pv[1][0]=-y*td-w*ct;
	pv[1][1]=x*td-w*st;
	pv[1][2]=rpd*cp+sp*rd;
}

void eraPv2s(double pv[2][3],double*theta,double*phi,double*r,double*td,
			 double*pd,double*rd){
	double x=pv[0][0];
	double y=pv[0][1];
	double z=pv[0][2];
	const double xd=pv[1][0];
	const double yd=pv[1][1];
	const double zd=pv[1][2];

	double rxy2=x*x+y*y;
	double r2=rxy2+z*z;
	const double rtrue=sqrt(r2);

	double rw=rtrue;
	if(rtrue==0.0){
		x=xd;
		y=yd;
		z=zd;
		rxy2=x*x+y*y;
		r2=rxy2+z*z;
		rw=sqrt(r2);
	}

	const double rxy=sqrt(rxy2);
	const double xyp=x*xd+y*yd;
	if(rxy2!=0.0){
		*theta=atan2(y,x);
		*phi=atan2(z,rxy);
		*td=(x*yd-y*xd)/rxy2;
		*pd=(zd*rxy2-z*xyp)/(r2*rxy);
	}else{
		*theta=0.0;
		*phi=(z!=0.0)?atan2(z,rxy):0.0;
		*td=0.0;
		*pd=0.0;
	}
	*r=rtrue;
	*rd=(rw!=0.0)?(xyp+z*zd)/rw:0.0;
}

void eraRxp(double r[3][3],double p[3],double rp[3]){
	double wrp[3];
	for(int row=0;row<3;++row){
		double sum=0.0;
		for(int col=0;col<3;++col){
			sum+=r[row][col]*p[col];
		}
		wrp[row]=sum;
	}
	eraCp(wrp,rp);
}

void eraTrxp(double r[3][3],double p[3],double trp[3]){
	const double x=p[0];
	const double y=p[1];
	const double z=p[2];

	const double tx=r[0][0]*x+r[1][0]*y+r[2][0]*z;
	const double ty=r[0][1]*x+r[1][1]*y+r[2][1]*z;
	const double tz=r[0][2]*x+r[1][2]*y+r[2][2]*z;

	trp[0]=tx;
	trp[1]=ty;
	trp[2]=tz;
}

void eraPvtob(double elong,double phi,double hm,double xp,double yp,double sp,
			  double theta,double pv[2][3]){
	static constexpr double kEarthRotationRate=
		1.00273781191135448*K_TWO_PI/K_SECONDS_PER_DAY;

	double xyzm[3];
	(void)eraGd2gc(K_ERFA_WGS84,elong,phi,hm,xyzm);

	double rpm[3][3];
	eraPom00(xp,yp,sp,rpm);

	double xyz[3];
	eraTrxp(rpm,xyzm,xyz);
	const double x=xyz[0];
	const double y=xyz[1];
	const double z=xyz[2];

	const double s=sin(theta);
	const double c=cos(theta);

	pv[0][0]=c*x-s*y;
	pv[0][1]=s*x+c*y;
	pv[0][2]=z;

	pv[1][0]=kEarthRotationRate*(-s*x-c*y);
	pv[1][1]=kEarthRotationRate*(c*x-s*y);
	pv[1][2]=0.0;
}

